/**
 * **서버 코드를 사람 말로 바꾸는 표. 두 앱이 같이 쓴다.**
 *
 * 여기 있는 것들은 전부 「같은 값을 두 앱이 다르게 말하면 안 되는」 것이다.
 * 같은 직원의 같은 주를 두고 관리팀 화면과 폰이 다른 말을 하면, 문의가 왔을 때
 * 어느 쪽이 맞는지 알 수가 없다.
 *
 * **원래는 두 앱이 각자 갖고 있었다** (`features/attendance/labels.ts` ·
 * `features/duty/labels.ts`). 두 파일 다 주석에 「한쪽을 고치면 다른 쪽도 고친다」고
 * 적어 뒀지만 그것을 지키는 것이 아무것도 없었다. 테스트로 막아 봤으나
 * **이 리포에는 CI가 없어서** 아무도 `npm test`를 치지 않으면 그 테스트도 주석과 같다.
 * 그래서 2026-09-03에 여기로 올렸다 — 어긋난 뒤에 알려주는 대신 어긋날 수 없게 한다.
 *
 * **여기에 두는 것과 두지 않는 것.**
 * - 둔다 — 서버가 준 코드·단계를 사람 말로 바꾸는 것
 * - 두지 않는다 — 한 앱에서만 쓰는 문구, 빈 값 처리, 자리에 따라 달라지는 표기.
 *   관리팀 표는 빈 칸에 `—`를 그려야 하고 모바일은 줄을 아예 안 그린다. **그 차이는
 *   자리의 성질이지 값의 뜻이 아니라서** 각 앱이 갖는다
 */

/** `StatusText`가 받는 색. 두 앱이 같은 이름을 쓴다 */
export type LabelTone = 'done' | 'error' | 'neutral';

/**
 * 52시간 알림 단계.
 *
 * **단계는 서버가 정한 `alertLevel`을 그대로 쓴다.** 분을 보고 다시 판단하지 않는다 —
 * 스키마가 "프런트가 분 단위로 다시 판단하면 서버와 기준이 어긋난다"고 적고 있다.
 */
const ALERT_LEVEL_LABEL: Record<number, string> = {
  0: '여유 있어요',
  1: '48시간을 넘겼어요',
  2: '52시간이 코앞이에요',
  3: '52시간을 넘겼어요',
};

export function alertLevelText(level: number): string {
  // 서버가 새 단계를 늘릴 수 있다. 모르는 값은 숫자를 그대로 보여주고 지어내지 않는다.
  return ALERT_LEVEL_LABEL[level] ?? `단계 ${level}`;
}

/**
 * **경고 색이 없어서 2단계와 3단계가 같은 빨강이다** (2026-09-03 확정. `DESIGN_RULES.md` 2장).
 *
 * 부족해서가 아니라 판단이다 — 넘긴 것과 넘길 것 둘 다 관리팀이 **지금 손대야 하는 줄**이라
 * 같은 무게로 둔다. 색을 하나 더 주면 둘 중 하나를 나중에 봐도 되는 것으로 만든다.
 * 구분은 문구가 한다.
 */
export function alertLevelTone(level: number): LabelTone {
  return level >= 2 ? 'error' : 'neutral';
}

/**
 * 경비교대 슬롯 코드. 명세서 1.4가 슬롯을 중식·석식으로 적고 있다.
 *
 * **빈 값은 여기서 다루지 않는다.** 관리팀 표는 `—`를 그려야 하고 모바일은 줄을 안 그린다 —
 * 부르는 쪽이 정한다. 여기는 **코드를 말로 바꾸는 것**만 한다.
 *
 * 모르는 코드는 서버가 준 값을 그대로 돌려준다. 지어내지 않는다 (`CLAUDE.md` 3장).
 */
export function slotName(slotCode: string): string {
  if (slotCode === 'LUNCH') return '중식';
  if (slotCode === 'DINNER') return '석식';
  return slotCode;
}
